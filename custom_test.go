func BenchmarkGenerateId(b *testing.B) {
	for i := 0; i < b.N; i++ {
		b.Logf("---------%v---------", i)
		b.Log(GenerateId(""))
		b.Log(GenerateId("Q"))
		b.Log(GenerateId("Q1"))
		b.Log(GenerateId("Q10000"))
		b.Log(GenerateId("Q172676"))
		b.Log(GenerateId("Q17267650"))
		b.Log(GenerateId(strconv.Itoa(i)))
	}
}
